"""Проверка автономной сессии: правильно ли она понимает, что случилось.

Эти решения принимаются, когда рядом никого нет. Ошибка в разборе стоит не
исключения, а недели: сессия либо крутит попытки впустую, либо уходит после
первой заминки, а следующая будет только через неделю квоты.

    py -3 synth1/test_session.py
"""

from __future__ import annotations

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))

from train.session import (compare_probes, decide,  # noqa: E402
                          read_holdout)
from synth1.test_model import FAILED, PASSED, check  # noqa: E402

# Куски настоящих логов — не выдуманные, а те, на которых мы уже спотыкались.
OOM = """  предполётная проверка:
ValueError: RESOURCE_EXHAUSTED: E0100: RuntimeBufferAllocationFailure:
Error allocating device buffer: Attempting to allocate 1.50G. That was not
possible. There are 339.94M free.; (1x2x0_HBM0)
"""

NAN = """шаг      50 | loss    nan | ppl      nan | lr 0.025 | |g|    nan
  веса отравлены: 214 тензоров, первые ["p['layers'][0]['attn']['q']"]

остановка: лосс перестал быть конечным
шагов за сессию: 50 за 0.04 ч
"""

TIME = """чекпоинт: шаг 12,000, 9.30 ГБ, 18.4с → checkpoints/pretrain/step-12000
на Hub: sekund0chka/synth-1-pretrain за 214с

остановка: лимит времени сессии
шагов за сессию: 12,000 за 8.19 ч
"""

STEPS = """остановка: заданное число шагов
шагов за сессию: 2,000 за 0.15 ч
loss: 9.952 → 3.607
"""

LOAD_OOM = """диск: снимок 9.30 ГБ, свободно 19.5 ГБ, держим локально 1
Fetching 2 files: 100%|##########| 2/2 [00:21<00:00, 10.79s/it]
Traceback (most recent call last):
  File "/kaggle/working/synth-1/train/pretrain.py", line 205, in main
    params, state, meta = C.load(local, params, state)
  File "/kaggle/working/synth-1/synth1/checkpoint.py", line 143, in load
    "m": _unflatten(flat, opt_state_ref["m"], "m"),
ValueError: RESOURCE_EXHAUSTED: E0100: RuntimeBufferAllocationFailure:
Error allocating device buffer: Attempting to allocate 54.00M. That was not
possible. There are 24.82M free.; (0x0x0_HBM0)
"""

STEP_OOM = """шаг      50 | loss  8.412 | ppl   4498.1 | lr 0.025 | |g|   1.20
шаг     100 | loss  7.980 | ppl   2926.3 | lr 0.050 | |g|   1.05
ValueError: RESOURCE_EXHAUSTED: E0100: RuntimeBufferAllocationFailure:
Error allocating device buffer: Attempting to allocate 1.50G.
"""

NETWORK = """    сеть: ConnectionError, повтор через 120с (8/20)
Traceback (most recent call last):
requests.exceptions.ConnectionError: не достучались до Hub
"""

# Лог сессии 29.08.2026: снимки писались, но ни один не уехал, и все 19,477
# шагов пропали вместе с контейнером.
NO_ROOM = """чекпоинт: шаг 16,000, 9.30 ГБ, 10.8с → checkpoints/pretrain/step-16000
на Hub НЕ ХВАТИЛО МЕСТА (Bad request for commit endpoint:
Private repository storage limit reached, please upgrade your plan).

остановка: снимок некуда девать: на Hub нет места
шагов за сессию: 2,000 за 0.9 ч
"""


def main():
    print("1. Каждая беда узнаётся по своему следу")
    check("нехватка памяти", decide(1, OOM) == "не влезло", decide(1, OOM))
    check("сорвавшийся лосс", decide(0, NAN) == "лосс сорвался", decide(0, NAN))
    check("время вышло", decide(0, TIME) == "время вышло", decide(0, TIME))
    check("прогон закончен", decide(0, STEPS) == "прогон закончен",
          decide(0, STEPS))
    full = ("RuntimeError: Task error: File reconstruction error: IO Error: "
            "No space left on device (os error 28)")
    check("диск полон — отдельный вердикт, а не «непонятная поломка»",
          decide(1, full) == "диск полон", decide(1, full))
    check("непонятная поломка", decide(1, NETWORK) == "непонятная поломка",
          decide(1, NETWORK))
    # Место на Hub — единственная беда, от которой перезапуск не спасает:
    # снимок уедет в ту же переполненную квоту.
    check("снимку некуда деваться",
          decide(0, NO_ROOM) == "снимок некуда девать", decide(0, NO_ROOM))

    print("\n2. Память на загрузке — не про батч")
    # Снимок приезжает до первого шага, и уменьшать там нечего: батч задаёт
    # размер активаций, а не вес модели. Сессия 28.08.2026 честно спустилась с
    # 32 до 8 и упала все три раза на одной и той же строке.
    check("нехватка на загрузке узнаётся",
          decide(1, LOAD_OOM) == "не влезло на загрузке", decide(1, LOAD_OOM))
    # А если шаги уже шли, то же сообщение означает ровно то, что написано:
    # активации не влезли, и меньший батч поможет.
    check("нехватка на шаге — обычная",
          decide(1, STEP_OOM) == "не влезло", decide(1, STEP_OOM))

    print("\n3. Порядок разбора")
    # Время вышло — это успех, даже если выше по логу мелькала беда: снимок
    # снят, сессия отработала. Перезапускать нечего.
    check("время важнее старой ошибки",
          decide(0, OOM + TIME) == "время вышло")
    # А вот нехватка памяти важнее кода возврата: она его и объясняет, и
    # реакция на неё осмысленная, в отличие от слепого повтора.
    check("память важнее кода возврата",
          decide(1, OOM + NETWORK) == "не влезло")
    # Сорвавшийся лосс приходит с нулевым кодом: прогон отработал штатно, сам
    # себя остановил и вышел. Без разбора хвоста это выглядело бы успехом.
    check("nan не выглядит успехом", decide(0, NAN) != "прогон закончен")

    print("\n4. Пустой лог")
    # Процесс, убитый по памяти самой машиной, не успевает ничего сказать.
    check("убитый без следов — поломка", decide(-9, "") == "непонятная поломка")
    check("тихий успех — успех", decide(0, "") == "прогон закончен")


    print("\n5. Проба LR читается из хвоста лога")
    good = ("отложенный лосс: 2.8741 (шаг 14,000) → 2.8102 (шаг 15,000), "
            "-0.0639 — учится")
    check("сдвиг вынут", read_holdout(good) == (2.8741, 2.8102, -0.0639),
          str(read_holdout(good)))
    check("нет строки — нет числа", read_holdout("шаг 100 | loss 3.0") is None)
    # Прогон, не доживший до второго замера, не должен притворяться
    # результатом: иначе проба соврёт, а на её выводе закрепят LR на недели.
    check("одного замера мало",
          read_holdout("  отложенный лосс 2.8741 (ppl 17.7), 12с") is None)

    print("\n6. Вердикт пробы")
    lower = {1.0: (2.87, 2.86, -0.01), 0.3: (2.87, 2.80, -0.07)}
    check("меньший LR выигрывает", "0.3" in compare_probes(lower),
          compare_probes(lower))
    same = {1.0: (2.87, 2.86, -0.0100), 0.3: (2.87, 2.86, -0.0102)}
    check("одинаковый сдвиг — плато ни при чём",
          "плато ни при чём" in compare_probes(same), compare_probes(same))
    check("одной пробы для вывода мало",
          "сравнивать нечего" in compare_probes({1.0: (2.87, 2.86, -0.01),
                                                 0.3: None}))

    print("\n7. Замер скорости не врёт молча")
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent
                          / "evals"))
    from speed import steady  # noqa: E402
    # Настоящий случай 05.09.2026: один конфиг, 11.1 с на двадцати шагах и
    # 20.6 с на десяти. Разница — компиляция, попавшая в таймер; напечатанный
    # тогда MFU 0.4% был занижен в четырнадцать раз.
    value, warning = steady([20.6, 11.1])
    check("разошедшиеся круги замечены", bool(warning), warning)
    check("берётся наименьший круг", value == 11.1, str(value))
    ровные = [1.689, 1.702, 1.695]
    value, warning = steady(ровные)
    check("ровные круги молчат", warning == "", warning)
    check("и дают наименьшее", value == 1.689, str(value))
    # Один круг не с чем сравнивать — предупреждать не о чем, но и не врать.
    check("один круг проходит", steady([1.5]) == (1.5, ""))

    print("\n8. Фильтр вариантов замера")
    from speed import pick  # noqa: E402
    план = [("как есть", 0, 0), ("без MoD", 0, 0),
            ("внимание целиком", 0, 0), ("внимание блоками 512", 0, 0)]
    имена = lambda p: [r[0] for r in p]  # noqa: E731
    # Без базовой строки сравнивать не с чем, поэтому она остаётся всегда,
    # даже если под фильтр не подходит.
    check("база остаётся всегда",
          "как есть" in имена(pick(план, "внимание")))
    # Имена подобраны с общим корнем: без этого фильтр «внимание» не совпал
    # бы со склонённым «блок внимания» и отдал бы неполный набор молча.
    check("лишнее отсеяно",
          имена(pick(план, "внимание")) ==
          ["как есть", "внимание целиком", "внимание блоками 512"],
          str(имена(pick(план, "внимание"))))
    check("пустой фильтр — весь план", pick(план, "") == план)
    # Опечатка в фильтре не должна тихо превратиться в замер одной строки:
    # полтора часа сессии ушли бы на число, из которого ничего не следует.
    try:
        pick(план, "чепуха")
        поймано = False
    except SystemExit:
        поймано = True
    check("опечатка в фильтре не проходит молча", поймано)

    print("\n9. Как часто снимок уезжает на Hub")
    # Заливка стоит 9.3 ГБ квоты и не возвращает их: удаление папок и
    # схлопывание истории оставляют блобы висеть до сборщика мусора Hub
    # (замер 08.09.2026). Сессия 07.09 залила семь снимков и встала на
    # восьмой, не досчитав полутора часов, — поэтому частота заливки
    # задаётся отдельно от частоты чекпоинтов.
    from train.pretrain import to_hub_now  # noqa: E402
    check("ноль — как раньше, каждый чекпоинт", to_hub_now(3000, 0, 1000))
    check("по своей сетке заливаем", to_hub_now(8000, 8000, 2000))
    check("между сетками — только на диск", not to_hub_now(6000, 8000, 2000))
    # Некратная сетка означает ноль заливок за сессию, то есть потерю
    # всего прогона — ровно ту, ради которой заливка и существует.
    try:
        to_hub_now(8000, 8000, 3000)
        поймано = False
    except SystemExit:
        поймано = True
    check("некратная сетка не проходит молча", поймано)
    print()
    print("10. Вердикт сессии считается по наклону, а не по двум точкам")
    from train.pretrain import holdout_trend  # noqa: E402
    # Настоящие 31 замер сессии 15.09.2026: лосс не двигался, а крайние точки
    # обе оказались низкими и дали ложное «учится» на -0.0431.
    flat = [(55030, 2.1285), (56000, 2.0972), (57000, 2.0848), (58000, 2.1379),
            (59000, 2.1071), (60000, 2.0989), (61000, 2.0967), (62000, 2.0829),
            (63000, 2.1386), (64000, 2.0760), (65000, 2.1496), (66000, 2.1305),
            (67000, 2.0894), (68000, 2.1365), (69000, 2.1460), (70000, 2.1022),
            (71000, 2.1142), (72000, 2.0910), (73000, 2.1377), (74000, 2.1011),
            (75000, 2.1434), (76000, 2.1366), (77000, 2.1136), (78000, 2.1037),
            (79000, 2.0939), (80000, 2.0647), (81000, 2.0858), (82000, 2.1520),
            (83000, 2.1344), (84000, 2.1139), (84425, 2.0854)]
    slope, t_stat, noise = holdout_trend(flat)
    check("плато видно по наклону", abs(t_stat) < 2, f"t={t_stat:+.2f}")
    check("крайние точки врут про спуск", flat[-1][1] - flat[0][1] < -0.04,
          f"{flat[-1][1] - flat[0][1]:+.4f} между крайними")
    check("шум замеров посчитан", 0.01 < noise < 0.05, f"шум {noise:.4f}")
    # Настоящий спуск обязан проходить порог: наклон отрезка 10,000-29,598.
    # Шум того же размера, что в настоящих замерах, иначе t уходит в бесконечность
    # и проверка перестаёт что-либо значить.
    wobble = [+0.02, -0.03, +0.01, -0.02, +0.03, -0.01, 0.0, +0.02, -0.03, +0.01]
    descent = [(10000 + i * 1000, 2.45 - 0.0107 * i + wobble[i % len(wobble)])
               for i in range(20)]
    slope_d, t_d, _ = holdout_trend(descent)
    check("спуск виден", t_d <= -2, f"t={t_d:+.2f}, наклон {slope_d:+.4f}")
    check("трёх замеров мало для тренда", holdout_trend(flat[:3]) is None)

    print(f"\n{'=' * 52}")
    print(f"пройдено {len(PASSED)}, провалено {len(FAILED)}")
    if FAILED:
        for name in FAILED:
            print(f"  FAIL {name}")
        sys.exit(1)


if __name__ == "__main__":
    main()

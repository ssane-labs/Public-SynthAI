"""Фильтры качества и нормализация документов, применяемые на лету.

Веб и математика приходят уже отфильтрованными: у fineweb-edu и finemath есть
классификатор образовательной ценности, добавить к нему нечего. Работа здесь —
про код.

Три задачи:

1. Отсев мусора. Правила простые и грубые: выбросить то, на чём учиться
   нечему — сгенерированное, вендоренное, сжатое машиной.
2. Снятие чужих служебных меток. StarCoderData вшивает в текст <reponame>,
   <filename> и <gh_stars> под свой токенизатор; у нас он свой, и эти строки
   для модели — шум, который она начнёт воспроизводить.
3. Отсев по лицензии — только для запасного github-code-clean, где 38% файлов
   под copyleft. У starcoderdata отбор сделан на стороне корпуса.
"""

from __future__ import annotations

import re

# Пути, которые почти всегда означают чужой или собранный код.
VENDOR_PATTERNS = re.compile(
    r"(^|/)("
    r"node_modules|bower_components|vendor|third_party|thirdparty|external|"
    r"dist|build|out|target|site-packages|__pycache__|\.git|"
    r"migrations|generated|gen|proto_gen"
    r")(/|$)",
    re.IGNORECASE,
)

MINIFIED_SUFFIX = re.compile(r"\.(min|bundle|pack|compiled)\.[a-z0-9]+$", re.IGNORECASE)

GENERATED_MARKERS = (
    "do not edit",
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "generated by",          # ловит «Generated by delombok», protoc, swagger, Sphinx
    "this file was generated",
    "@generated",
    "choose license headers in project properties",   # пустой шаблон NetBeans
)

# Пороговые значения. Подобраны так, чтобы резать очевидное и не трогать
# нормальный код; если на этапе A выяснится, что режем полезное — правятся здесь.
MIN_CHARS = 200
MAX_CHARS = 100_000
MIN_LINES = 3
MAX_LINE_LEN = 1000          # длиннее — почти наверняка минификация
MAX_MEAN_LINE_LEN = 100
MIN_ALPHA_FRACTION = 0.25    # ниже — данные, а не код: base64, дампы, бинарь
MIN_UNIQUE_LINE_FRACTION = 0.3


def keep_code(row: dict) -> bool:
    """Стоит ли учиться на этом файле."""
    text = row.get("text") or ""
    if not (MIN_CHARS <= len(text) <= MAX_CHARS):
        return False

    # Поле с путём называется по-разному: path у github-code-clean,
    # max_stars_repo_path у starcoderdata.
    path = row.get("path") or row.get("max_stars_repo_path") or ""
    if VENDOR_PATTERNS.search(path) or MINIFIED_SUFFIX.search(path):
        return False

    head = text[:2000].lower()
    if any(marker in head for marker in GENERATED_MARKERS):
        return False

    lines = text.split("\n")
    if len(lines) < MIN_LINES:
        return False

    lengths = [len(ln) for ln in lines]
    if max(lengths) > MAX_LINE_LEN:
        return False
    if sum(lengths) / len(lengths) > MAX_MEAN_LINE_LEN:
        return False

    alpha = sum(ch.isalpha() for ch in text)
    if alpha / len(text) < MIN_ALPHA_FRACTION:
        return False

    # Повторяющиеся строки — признак сгенерированных таблиц и дампов.
    stripped = [ln.strip() for ln in lines if ln.strip()]
    if stripped:
        unique = len(set(stripped)) / len(stripped)
        if unique < MIN_UNIQUE_LINE_FRACTION:
            return False

    return True


# --- Лицензии ---------------------------------------------------------------
# Пермиссивные: разрешают коммерческое использование и производные работы без
# требования открыть исходники. Всё остальное — copyleft, и в корпус модели,
# которую предполагается продавать, ему не место. Обоснование — LICENSES.md.
PERMISSIVE_LICENSES = {
    "mit", "apache-2.0", "bsd-3-clause", "bsd-2-clause", "bsd-2-clause-freebsd",
    "isc", "unlicense", "cc0-1.0", "0bsd", "zlib", "postgresql", "ncsa",
    "artistic-2.0", "python-2.0", "wtfpl", "cc-by-4.0",
}


def keep_licensed_code(row: dict) -> bool:
    """То же, что keep_code, плюс отсев copyleft по объявленной лицензии.

    Замер на первых 10 000 файлов github-code-clean: MIT 58.1%, GPL-3.0 19.4%,
    GPL-2.0 18.8%, MPL 1.5%, EPL 1.1%, остальное по мелочи. Пермиссивных 60.6%.
    """
    if (row.get("license") or "").lower() not in PERMISSIVE_LICENSES:
        return False
    return keep_code(row)


# --- Нормализация -----------------------------------------------------------
# Метки StarCoderData: идут первыми строками файла, каждая на своей строке.
STARCODER_MARKERS = re.compile(
    r"\A(?:<(?:reponame|filename|gh_stars|issue_start|issue_closed)>[^\n]*\n?)+"
)


def strip_starcoder_markers(text: str) -> str:
    return STARCODER_MARKERS.sub("", text)


NORMALISE_BY_LANG = {
    "code": strip_starcoder_markers,
}


def normalise(row: dict, lang: str) -> dict:
    fn = NORMALISE_BY_LANG.get(lang)
    if fn is not None:
        row["text"] = fn(row["text"])
    return row


# Какой фильтр применять к какому языку источника. Источники объявляют свой
# lang в mixture.yaml; всё, для чего фильтра нет, проходит как есть.
BY_LANG = {
    "code": keep_code,
    "code-licensed": keep_licensed_code,
}


def keep(row: dict, lang: str) -> bool:
    fn = BY_LANG.get(lang)
    return True if fn is None else fn(row)

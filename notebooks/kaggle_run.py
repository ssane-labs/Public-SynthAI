def sh(*cmd):
    return subprocess.run(cmd, capture_output=True, text=True).stdout.strip()

def free_gb(path="/kaggle/working"):
    s = os.statvfs(path)
    return s.f_bavail * s.f_frsize / 1024**3

def left_hours():
    return SESSION_HOURS - (time.time() - T0) / 3600

SECRETS = []          # значения, которых не должно быть в логе

def mask(text):
    """Убрать секреты из строки перед печатью.

    Токен уезжает в команду `git clone`, а лог ноутбука сохраняется вместе с
    версией и виден всем, кому её показывают. Один раз напечатать достаточно,
    чтобы токен пришлось отзывать.
    """
    for secret in SECRETS:
        if secret:
            text = text.replace(secret, "***")
    return text

def run(*cmd, check=True):
    """Запуск с выводом по мере появления.

    Именно по мере появления, а не в конце. Прогон идёт восемь часов, и если
    собирать его вывод в память, то при обрыве сессии в логе не останется
    ничего — ни лосса, ни причины. Возвращаем код и хвост, по хвосту
    разбираемся, что случилось.
    """
    print("$", mask(" ".join(cmd)), flush=True)
    env = {**os.environ, "PYTHONUNBUFFERED": "1"}
    p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                         text=True, bufsize=1, env=env)
    tail = []
    for line in p.stdout:
        line = mask(line)
        print(line, end="", flush=True)
        tail.append(line)
        if len(tail) > 500:
            tail.pop(0)
    p.wait()
    print(f"[код {p.returncode}, свободно {free_gb():.1f} ГБ, "
          f"осталось {left_hours():.1f} ч]", flush=True)
    if p.returncode and check:
        raise SystemExit(mask(f"упало: {' '.join(cmd)}"))
    return p.returncode, "".join(tail)

